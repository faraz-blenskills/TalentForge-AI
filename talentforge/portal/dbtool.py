"""Database maintenance for Supabase / Postgres.

  python -m portal.dbtool schema          write supabase/schema.sql (paste into the Supabase SQL editor)
  python -m portal.dbtool init            create the tables on DATABASE_URL and turn on row-level security
  python -m portal.dbtool check           connect, verify tables + RLS, do a write/read/delete round trip
  python -m portal.dbtool migrate-sqlite  copy local SQLite data into the Postgres database

DATABASE_URL is read from the environment or from .env. The connection string is never printed.
"""
from __future__ import annotations

import argparse
import sqlite3
import sys
from pathlib import Path

from app import db

from . import store

ROOT = Path(__file__).resolve().parent.parent
# parents before children, so foreign keys are satisfied while copying
COPY_ORDER = ["users", "organisations", "candidate_profiles", "jobs", "applications", "decisions", "ai_results",
              "audit_events", "narrative_cache", "resumes", "job_agents", "agent_runs", "job_results"]


def all_tables() -> list[str]:
    return db.table_names(db.SCHEMA, store.SCHEMA)


def schema_sql() -> str:
    parts = [
        "-- TalentForge AI - Supabase / Postgres schema (generated by `python -m portal.dbtool schema`).",
        "-- Safe to run more than once.",
        db.schema_to_pg(db.SCHEMA).strip(),
        db.schema_to_pg(store.SCHEMA).strip(),
        "ALTER TABLE users ADD COLUMN IF NOT EXISTS auth_uid TEXT;",
        "CREATE UNIQUE INDEX IF NOT EXISTS users_auth_uid_idx ON users(auth_uid);",
    ]
    for name, ddl in store._RESUME_MIGRATIONS:
        parts.append(f"ALTER TABLE resumes ADD COLUMN IF NOT EXISTS {name} {db.schema_to_pg(ddl)};")
    parts.append("-- The browser-facing (anon) key must not be able to read anything through Supabase's REST API.\n"
                 "-- With RLS enabled and no policies, only this server's database role can access the tables.")
    parts.append(db.rls_sql(all_tables()))
    return "\n\n".join(parts) + "\n"


def _require_pg() -> None:
    if not db.USE_PG:
        raise SystemExit("DATABASE_URL is not set to a postgres:// URL. Put it in .env (see .env.example).")


DEFAULT_POOLER_HOST = "aws-0-ap-northeast-1.pooler.supabase.com"


def build_database_url(project_ref: str, password: str, host: str = DEFAULT_POOLER_HOST, port: int = 6543) -> str:
    """Supabase pooler URL with the password percent-encoded (so characters like @ : / # are safe)."""
    from urllib.parse import quote
    return f"postgresql://postgres.{project_ref}:{quote(password, safe='')}@{host}:{port}/postgres"


def update_env_file(path: Path, key: str, value: str) -> None:
    """Set KEY=value in a .env file, replacing an existing (or commented template) line, keeping the rest."""
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    out, done = [], False
    for ln in lines:
        s = ln.strip()
        if s.startswith(f"{key}=") and not done:
            out.append(f"{key}={value}")
            done = True
        elif s.startswith(f"# {key}=") or s.startswith(f"#{key}="):
            continue                                     # drop the commented template
        else:
            out.append(ln)
    if not done:
        out.append(f"{key}={value}")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def cmd_set_url(args) -> int:
    """Prompt (hidden) for the database password, store DATABASE_URL in .env, then verify the connection."""
    import getpass
    import os
    import re
    import subprocess

    from app.config import load_env
    load_env()
    m = re.match(r"https://([a-z0-9]+)\.supabase\.co", os.environ.get("SUPABASE_URL", ""))
    ref = args.ref or (m.group(1) if m else "")
    if not ref:
        raise SystemExit("Set SUPABASE_URL in .env first (or pass --ref <project-ref>).")
    pw = getpass.getpass(f"Database password for project {ref} (typing is hidden): ")
    if not pw:
        raise SystemExit("No password entered; nothing changed.")
    update_env_file(ROOT / ".env", "DATABASE_URL", build_database_url(ref, pw, args.host, args.port))
    print("Saved DATABASE_URL to .env (the password is not shown).")
    if args.no_check:
        return 0
    print("Checking the connection...")
    return subprocess.call([sys.executable, "-m", "portal.dbtool", "check"], cwd=str(ROOT))


def cmd_schema(args) -> int:
    out = ROOT / "supabase" / "schema.sql"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(schema_sql(), encoding="utf-8")
    print(f"Wrote {out}")
    return 0


def cmd_init(args) -> int:
    _require_pg()
    store.init()
    with db.connect() as c:
        c.executescript(db.rls_sql(all_tables()))
    print("Schema applied and row-level security enabled on", len(all_tables()), "tables.")
    return 0


def cmd_check(args) -> int:
    _require_pg()
    problems: list[str] = []
    with db.connect() as c:
        ver = c.execute("SELECT version() AS v").fetchone()["v"]
        print("Connected:", ver.split(",")[0])
        have = {r["table_name"] for r in c.execute(
            "SELECT table_name FROM information_schema.tables WHERE table_schema=current_schema()").fetchall()}
        missing = [t for t in all_tables() if t not in have]
        print("Tables:", f"{len(all_tables()) - len(missing)}/{len(all_tables())} present")
        if missing:
            problems.append("missing tables (run `python -m portal.dbtool init`): " + ", ".join(missing))
        rls = {r["relname"]: r["relrowsecurity"] for r in c.execute(
            "SELECT c.relname, c.relrowsecurity FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace "
            "WHERE n.nspname=current_schema() AND c.relkind='r'").fetchall()}
        exposed = [t for t in all_tables() if t in rls and not rls[t]]
        print("Row-level security:", "enabled on all tables" if not exposed else f"MISSING on {len(exposed)} table(s)")
        if exposed:
            problems.append("RLS is off for: " + ", ".join(exposed) + " (run init) - the public anon key could "
                            "read these tables")
    # write / read / delete round trip through the same helpers the app uses
    try:
        rid = db.run("INSERT INTO audit_events(actor_id, action, ref, detail, created_at) VALUES (?,?,?,?,?)",
                     (None, "dbtool_check", "", "round-trip probe", db.now()))
        got = db.one("SELECT action FROM audit_events WHERE id=?", (rid,))
        db.run("DELETE FROM audit_events WHERE id=?", (rid,))
        print("Round trip:", "ok" if got and got["action"] == "dbtool_check" else "FAILED")
        if not got:
            problems.append("could not read back the probe row")
    except Exception as e:                       # report the failure; never hide it
        problems.append(f"round trip failed: {type(e).__name__}: {e}")
    for p in problems:
        print("PROBLEM:", p)
    return 1 if problems else 0


def cmd_migrate(args) -> int:
    _require_pg()
    src = Path(args.path or db.DB_PATH)
    if not src.exists():
        raise SystemExit(f"SQLite file not found: {src}")
    store.init()
    sl = sqlite3.connect(src)
    sl.row_factory = sqlite3.Row
    have = {r[0] for r in sl.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    total = 0
    only = sorted({int(i) for i in (args.user_id or [])})
    # With --user-id, copy only that person's portal data (no demo accounts, no employer/prototype tables)
    scoped = {
        "users": "id IN ({u})",
        "candidate_profiles": "user_id IN ({u})",
        "resumes": "user_id IN ({u})",
        "job_agents": "user_id IN ({u})",
        "agent_runs": "agent_id IN (SELECT id FROM job_agents WHERE user_id IN ({u}))",
        "job_results": "user_id IN ({u})",
    }
    for table in COPY_ORDER:
        if table not in have:
            continue
        if only:
            if table not in scoped:
                continue
            where = scoped[table].format(u=",".join(str(i) for i in only))
            rows = sl.execute(f"SELECT * FROM {table} WHERE {where}").fetchall()
        else:
            rows = sl.execute(f"SELECT * FROM {table}").fetchall()
        if not rows:
            continue
        cols = rows[0].keys()
        sql = f"INSERT OR IGNORE INTO {table}({', '.join(cols)}) VALUES ({', '.join('?' for _ in cols)})"
        with db.connect() as c:
            for r in rows:
                c.execute(sql, tuple(r[k] for k in cols))
        total += len(rows)
        print(f"  {table}: {len(rows)} row(s)")
    # keep the id sequences ahead of the copied rows
    with db.connect() as c:
        for table in COPY_ORDER:
            if table in ("candidate_profiles", "narrative_cache"):
                continue
            c._conn.execute(
                f"SELECT setval(pg_get_serial_sequence('{table}','id'), "
                f"GREATEST(COALESCE((SELECT MAX(id) FROM {table}), 0), 1))")
    print(f"Copied {total} row(s) from {src}.")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="portal.dbtool")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("schema").set_defaults(fn=cmd_schema)
    sub.add_parser("init").set_defaults(fn=cmd_init)
    sub.add_parser("check").set_defaults(fn=cmd_check)
    u = sub.add_parser("set-database-url", help="prompt for the DB password and write DATABASE_URL to .env")
    u.add_argument("--ref", help="Supabase project ref (default: taken from SUPABASE_URL)")
    u.add_argument("--host", default=DEFAULT_POOLER_HOST)
    u.add_argument("--port", type=int, default=6543)
    u.add_argument("--no-check", action="store_true")
    u.set_defaults(fn=cmd_set_url)
    m = sub.add_parser("migrate-sqlite")
    m.add_argument("--path", help="SQLite file to copy (default: the local talentforge.db)")
    m.add_argument("--user-id", type=int, action="append",
                   help="copy only this local user's portal data (repeatable); default copies everything")
    m.set_defaults(fn=cmd_migrate)
    args = ap.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
